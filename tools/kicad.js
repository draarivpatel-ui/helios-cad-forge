'use strict';
/**
 * Generates the KiCad 8 project, schematic and PCB files from hardware.js and
 * the pad data in tools/footprints.json (extracted from the official KiCad
 * footprint library). Output is deterministic: identifiers are derived from
 * a hash, so running the build twice gives byte-identical files.
 *
 * The generated PCB holds placed footprints, nets, an outline and a ground
 * zone. It has no routed tracks. The files have not been opened in KiCad.
 */
const crypto = require('node:crypto');
const path = require('node:path');
const fs = require('node:fs');
const HW = require('../hardware.js');

const FOOTPRINTS = JSON.parse(fs.readFileSync(path.join(__dirname, 'footprints.json'), 'utf8'));
const PROJECT = 'helios_mppt_node';
const SCH_VERSION = '20231120';
const PCB_VERSION = '20240108';

function uuid(seed) {
  const h = crypto.createHash('sha1').update('helios-6:' + seed).digest('hex');
  const variant = ((parseInt(h.slice(16, 18), 16) & 0x3f) | 0x80).toString(16);
  return [h.slice(0, 8), h.slice(8, 12), '4' + h.slice(13, 16), variant + h.slice(18, 20), h.slice(20, 32)].join('-');
}

function num(n) {
  const s = Number(n.toFixed(4)).toString();
  return s === '-0' ? '0' : s;
}

function q(s) {
  return JSON.stringify(String(s));
}

const FONT = '(effects (font (size 1.27 1.27)))';
const FONT_HIDDEN = '(effects (font (size 1.27 1.27)) (hide yes))';

/* ------------------------------------------------------------- schematic */

function symbolLayout(symbolKey) {
  const pinList = HW.SYMBOLS[symbolKey].pins;
  const left = Math.ceil(pinList.length / 2);
  const rows = Math.max(left, pinList.length - left);
  const top = ((rows - 1) * 2.54) / 2;
  const placed = pinList.map((pin, i) => {
    const onLeft = i < left;
    const row = onLeft ? i : i - left;
    return { pin, x: onLeft ? -12.7 : 12.7, y: top - row * 2.54, angle: onLeft ? 0 : 180, side: onLeft ? 'left' : 'right' };
  });
  return { placed, halfHeight: top + 2.54 };
}

function libSymbol(symbolKey, footprintHint) {
  const def = HW.SYMBOLS[symbolKey];
  const { placed, halfHeight } = symbolLayout(symbolKey);
  const lines = [];
  lines.push('    (symbol ' + q('Helios:' + symbolKey));
  lines.push('      (pin_names (offset 1.016))');
  lines.push('      (exclude_from_sim no) (in_bom yes) (on_board yes)');
  lines.push('      (property "Reference" ' + q(def.prefix) + ' (at 0 ' + num(halfHeight + 2.54) + ' 0) ' + FONT + ')');
  lines.push('      (property "Value" ' + q(symbolKey) + ' (at 0 ' + num(-halfHeight - 2.54) + ' 0) ' + FONT + ')');
  lines.push('      (property "Footprint" ' + q(footprintHint) + ' (at 0 0 0) ' + FONT_HIDDEN + ')');
  lines.push('      (property "Datasheet" "" (at 0 0 0) ' + FONT_HIDDEN + ')');
  lines.push('      (property "Description" "" (at 0 0 0) ' + FONT_HIDDEN + ')');
  lines.push('      (symbol ' + q(symbolKey + '_0_1'));
  lines.push('        (rectangle (start -7.62 ' + num(halfHeight) + ') (end 7.62 ' + num(-halfHeight) +
    ') (stroke (width 0.254) (type default)) (fill (type background)))');
  lines.push('      )');
  lines.push('      (symbol ' + q(symbolKey + '_1_1'));
  placed.forEach((p) => {
    lines.push('        (pin ' + p.pin.type + ' line (at ' + num(p.x) + ' ' + num(p.y) + ' ' + p.angle + ') (length 5.08) ' +
      '(name ' + q(p.pin.name) + ' ' + FONT + ') (number ' + q(p.pin.number) + ' ' + FONT + '))');
  });
  lines.push('      )');
  lines.push('    )');
  return lines.join('\n');
}

function schematicPositions() {
  const positions = {};
  positions.U1 = [90, 160];
  const others = HW.COMPONENTS.filter((c) => c.ref !== 'U1');
  const cols = 6;
  const cellW = 66;
  let y = 40;
  let rowMax = 0;
  others.forEach((c, i) => {
    const col = i % cols;
    const half = symbolLayout(c.symbol).halfHeight;
    if (col === 0 && i > 0) {
      y += rowMax + 14;
      rowMax = 0;
    }
    rowMax = Math.max(rowMax, half * 2);
    positions[c.ref] = [190 + col * cellW, y + half];
  });
  return positions;
}

function generateSchematic() {
  const rootUuid = uuid('schematic-root');
  const pinNet = HW.buildPinNetMap();
  const positions = schematicPositions();
  const out = [];
  out.push('(kicad_sch');
  out.push('  (version ' + SCH_VERSION + ')');
  out.push('  (generator "helios_forge")');
  out.push('  (generator_version "8.0")');
  out.push('  (uuid ' + q(rootUuid) + ')');
  out.push('  (paper "A2")');
  out.push('  (title_block (title "Helios-6 MPPT telemetry node") (date "2026-10-25") (rev "A")');
  out.push('    (comment 1 "Generated by tools/build-artifacts.js. Not opened in KiCad."))');
  out.push('  (lib_symbols');
  const seen = {};
  HW.COMPONENTS.forEach((c) => {
    if (!seen[c.symbol]) {
      seen[c.symbol] = 1;
      out.push(libSymbol(c.symbol, c.footprint));
    }
  });
  out.push('  )');
  HW.COMPONENTS.forEach((c) => {
    const [sx, sy] = positions[c.ref];
    const { placed, halfHeight } = symbolLayout(c.symbol);
    out.push('  (symbol (lib_id ' + q('Helios:' + c.symbol) + ') (at ' + num(sx) + ' ' + num(sy) + ' 0) (unit 1)');
    out.push('    (exclude_from_sim no) (in_bom yes) (on_board yes) (dnp no)');
    out.push('    (uuid ' + q(uuid('sym-' + c.ref)) + ')');
    out.push('    (property "Reference" ' + q(c.ref) + ' (at ' + num(sx) + ' ' + num(sy - halfHeight - 3.5) + ' 0) ' + FONT + ')');
    out.push('    (property "Value" ' + q(c.value) + ' (at ' + num(sx) + ' ' + num(sy + halfHeight + 3.5) + ' 0) ' + FONT + ')');
    out.push('    (property "Footprint" ' + q(c.footprint) + ' (at ' + num(sx) + ' ' + num(sy) + ' 0) ' + FONT_HIDDEN + ')');
    out.push('    (property "Datasheet" "" (at ' + num(sx) + ' ' + num(sy) + ' 0) ' + FONT_HIDDEN + ')');
    out.push('    (property "MPN" ' + q(c.mpn) + ' (at ' + num(sx) + ' ' + num(sy) + ' 0) ' + FONT_HIDDEN + ')');
    out.push('    (property "LCSC" ' + q(c.lcsc) + ' (at ' + num(sx) + ' ' + num(sy) + ' 0) ' + FONT_HIDDEN + ')');
    placed.forEach((p) => {
      out.push('    (pin ' + q(p.pin.number) + ' (uuid ' + q(uuid('pin-' + c.ref + '-' + p.pin.number)) + '))');
    });
    out.push('    (instances (project ' + q(PROJECT) + ' (path ' + q('/' + rootUuid) + ' (reference ' + q(c.ref) + ') (unit 1))))');
    out.push('  )');
  });
  HW.COMPONENTS.forEach((c) => {
    const [sx, sy] = positions[c.ref];
    symbolLayout(c.symbol).placed.forEach((p) => {
      const px = sx + p.x;
      const py = sy - p.y;
      const key = c.ref + '.' + p.pin.number;
      const net = pinNet[key];
      if (net) {
        const justify = p.side === 'left' ? 'right' : 'left';
        const angle = p.side === 'left' ? 180 : 0;
        out.push('  (global_label ' + q(net) + ' (shape bidirectional) (at ' + num(px) + ' ' + num(py) + ' ' + angle + ')');
        out.push('    (fields_autoplaced yes) (effects (font (size 1.27 1.27)) (justify ' + justify + '))');
        out.push('    (uuid ' + q(uuid('label-' + key)) + ')');
        out.push('    (property "Intersheetrefs" "${INTERSHEET_REFS}" (at ' + num(px) + ' ' + num(py) + ' 0) ' + FONT_HIDDEN + '))');
      } else if (HW.NO_CONNECT[key] !== undefined) {
        out.push('  (no_connect (at ' + num(px) + ' ' + num(py) + ') (uuid ' + q(uuid('nc-' + key)) + '))');
      }
    });
  });
  out.push('  (sheet_instances (path "/" (page "1")))');
  out.push(')');
  return out.join('\n') + '\n';
}

/* ------------------------------------------------------------------- pcb */

function netIndexMap() {
  const names = ['GND'].concat(Object.keys(HW.NETS).filter((n) => n !== 'GND').sort());
  const map = {};
  names.forEach((n, i) => { map[n] = i + 1; });
  return { names, map };
}

function padLine(pad, netName, netId, seed, isSmd) {
  const at = '(at ' + num(pad.x) + ' ' + num(pad.y) + (pad.r ? ' ' + num(pad.r) : '') + ')';
  const size = '(size ' + num(pad.w) + ' ' + num(pad.h) + ')';
  const layers = '(layers ' + pad.layers.map(q).join(' ') + ')';
  let drill = '';
  if (pad.drill) {
    drill = pad.drill.length === 2 ? ' (drill oval ' + num(pad.drill[0]) + ' ' + num(pad.drill[1]) + ')' : ' (drill ' + num(pad.drill[0]) + ')';
  }
  const rr = pad.s === 'roundrect' ? ' (roundrect_rratio ' + num(pad.rr || 0.25) + ')' : '';
  const net = netName ? ' (net ' + netId + ' ' + q(netName) + ')' : '';
  const kind = pad.t === 'np_thru_hole' ? 'np_thru_hole' : (isSmd ? 'smd' : pad.t);
  return '    (pad ' + q(pad.n) + ' ' + kind + ' ' + pad.s + ' ' + at + ' ' + size + drill + ' ' + layers + rr + net +
    ' (uuid ' + q(uuid(seed)) + '))';
}

function footprintBlock(c, pinNet, netMap) {
  const data = FOOTPRINTS[c.footprint];
  if (!data) {
    throw new Error('no pad data for ' + c.footprint);
  }
  const [x, y, rot] = HW.PLACEMENT[c.ref] || [0, 0, 0];
  const isSmd = data.attr.indexOf('smd') >= 0;
  const out = [];
  out.push('  (footprint ' + q(c.footprint));
  out.push('    (layer "F.Cu")');
  out.push('    (uuid ' + q(uuid('fp-' + c.ref)) + ')');
  out.push('    (at ' + num(x) + ' ' + num(y) + (rot ? ' ' + num(rot) : '') + ')');
  out.push('    (property "Reference" ' + q(c.ref) + ' (at 0 ' + num((data.courtyard ? data.courtyard[1] : -2) - 0.8) + ' 0) (layer "F.SilkS") (uuid ' +
    q(uuid('fpref-' + c.ref)) + ') (effects (font (size 1 1) (thickness 0.15))))');
  out.push('    (property "Value" ' + q(c.value) + ' (at 0 ' + num((data.courtyard ? data.courtyard[3] : 2) + 0.8) + ' 0) (layer "F.Fab") (uuid ' +
    q(uuid('fpval-' + c.ref)) + ') (effects (font (size 1 1) (thickness 0.15))))');
  out.push('    (property "Footprint" ' + q(c.footprint) + ' (at 0 0 0) (unlocked yes) (layer "F.Fab") (hide yes) (uuid ' +
    q(uuid('fpfoot-' + c.ref)) + ') (effects (font (size 1.27 1.27))))');
  out.push('    (property "LCSC" ' + q(c.lcsc) + ' (at 0 0 0) (unlocked yes) (layer "F.Fab") (hide yes) (uuid ' +
    q(uuid('fplcsc-' + c.ref)) + ') (effects (font (size 1.27 1.27))))');
  out.push('    (attr ' + (isSmd ? 'smd' : 'through_hole') + ')');
  if (data.courtyard) {
    out.push('    (fp_rect (start ' + num(data.courtyard[0]) + ' ' + num(data.courtyard[1]) + ') (end ' + num(data.courtyard[2]) + ' ' +
      num(data.courtyard[3]) + ') (stroke (width 0.05) (type default)) (fill none) (layer "F.CrtYd") (uuid ' +
      q(uuid('fpcrt-' + c.ref)) + '))');
  }
  data.pads.forEach((pad, i) => {
    const net = pad.n ? pinNet[c.ref + '.' + pad.n] : undefined;
    out.push(padLine(pad, net, net ? netMap[net] : 0, 'pad-' + c.ref + '-' + i, isSmd));
  });
  out.push('  )');
  return out.join('\n');
}

function generatePcb() {
  const pinNet = HW.buildPinNetMap();
  const { names, map } = netIndexMap();
  const b = HW.BOARD;
  const out = [];
  out.push('(kicad_pcb');
  out.push('  (version ' + PCB_VERSION + ')');
  out.push('  (generator "helios_forge")');
  out.push('  (generator_version "8.0")');
  out.push('  (general (thickness ' + b.thickness + ') (legacy_teardrops no))');
  out.push('  (paper "A4")');
  out.push('  (title_block (title "Helios-6 MPPT telemetry node") (date "2026-10-25") (rev "A")');
  out.push('    (comment 1 "Placement and netlist only. No routed tracks. Not opened in KiCad."))');
  out.push('  (layers');
  out.push('    (0 "F.Cu" signal) (31 "B.Cu" signal)');
  out.push('    (32 "B.Adhes" user "B.Adhesive") (33 "F.Adhes" user "F.Adhesive")');
  out.push('    (34 "B.Paste" user) (35 "F.Paste" user)');
  out.push('    (36 "B.SilkS" user "B.Silkscreen") (37 "F.SilkS" user "F.Silkscreen")');
  out.push('    (38 "B.Mask" user) (39 "F.Mask" user)');
  out.push('    (40 "Dwgs.User" user "User.Drawings") (41 "Cmts.User" user "User.Comments")');
  out.push('    (42 "Eco1.User" user "User.Eco1") (43 "Eco2.User" user "User.Eco2")');
  out.push('    (44 "Edge.Cuts" user) (45 "Margin" user)');
  out.push('    (46 "B.CrtYd" user "B.Courtyard") (47 "F.CrtYd" user "F.Courtyard")');
  out.push('    (48 "B.Fab" user) (49 "F.Fab" user)');
  out.push('  )');
  out.push('  (setup (pad_to_mask_clearance 0))');
  out.push('  (net 0 "")');
  names.forEach((n) => { out.push('  (net ' + map[n] + ' ' + q(n) + ')'); });
  HW.COMPONENTS.forEach((c) => { out.push(footprintBlock(c, pinNet, map)); });
  out.push('  (gr_rect (start 0 0) (end ' + b.width + ' ' + b.height + ') (stroke (width 0.1) (type default)) (fill none) (layer "Edge.Cuts") (uuid ' +
    q(uuid('outline')) + '))');
  out.push('  (zone (net ' + map.GND + ') (net_name "GND") (layer "B.Cu") (uuid ' + q(uuid('zone-gnd')) + ')');
  out.push('    (hatch edge 0.5) (connect_pads (clearance 0.3)) (min_thickness 0.2) (filled_areas_thickness no)');
  out.push('    (fill yes (thermal_gap 0.3) (thermal_bridge_width 0.3))');
  out.push('    (polygon (pts (xy 0.5 0.5) (xy ' + (b.width - 0.5) + ' 0.5) (xy ' + (b.width - 0.5) + ' ' + (b.height - 0.5) + ') (xy 0.5 ' + (b.height - 0.5) + '))))');
  out.push(')');
  return out.join('\n') + '\n';
}

function generateProject() {
  return JSON.stringify({
    board: { design_settings: { defaults: { board_outline_line_width: 0.1, copper_line_width: 0.2 } } },
    meta: { filename: PROJECT + '.kicad_pro', version: 1 },
    schematic: { drawing: { default_line_thickness: 6.0 } }
  }, null, 2) + '\n';
}

/** Courtyard rectangle of a placed part in board millimetres. */
function placedCourtyard(ref) {
  const c = HW.componentByRef(ref);
  const data = FOOTPRINTS[c.footprint];
  const [x, y, rot] = HW.PLACEMENT[ref];
  const cy = data.courtyard;
  const corners = [[cy[0], cy[1]], [cy[2], cy[1]], [cy[2], cy[3]], [cy[0], cy[3]]].map(([px, py]) => {
    const a = (rot * Math.PI) / 180;
    return [x + px * Math.cos(a) - py * Math.sin(a), y + px * Math.sin(a) + py * Math.cos(a)];
  });
  const xs = corners.map((p) => p[0]);
  const ys = corners.map((p) => p[1]);
  return { x0: Math.min(...xs), y0: Math.min(...ys), x1: Math.max(...xs), y1: Math.max(...ys) };
}

module.exports = {
  PROJECT, uuid, FOOTPRINTS, generateSchematic, generatePcb, generateProject, placedCourtyard, symbolLayout
};
